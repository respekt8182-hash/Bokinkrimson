const titleMatchers: Array<[AttractionTemplateType, RegExp]> = [
  ["cave", /пещер(?:а|ы|е|у|ой|ами)(?:\s|$)|карст|подземн/iu],
  ["beach", /пляж|набережн|бухт/iu],
  ["religious", /храм|монастыр|церков|собор|мечет|часовн/iu],
  ["waterfall_water", /водопад|озер|озёр|источник|родник|река/iu],
  ["palace_architecture", /дворец|дача|усадьб|замок/iu],
  ["museum_history", /музей|крепост|городищ|мемориал|батаре|башн|памятник/iu],
  ["nature_route", /гора|скал|мыс|троп|плато|яйл/iu],
];

const categoryMatchers: Array<[AttractionTemplateType, RegExp]> = [
  ["beach", /пляжи|купание|пляж/iu],
  ["palace_architecture", /дворцы|дачи|архитектур|усадьб/iu],
  ["museum_history", /музеи|культур|памятник|истори|археолог|военн/iu],
  ["waterfall_water", /водопад|озер|озёр|водо[её]м/iu],
  ["religious", /храмы|монастыри|религи/iu],
  // The broad catalog category also contains caves; a cave title is handled above.
  ["nature_route", /горы|скалы|природа/iu],
];

export function determineAttractionTemplate(
  place: AttractionTemplateInput,
): AttractionTemplateType {
  const title = place.title?.trim() ?? "";
  const titleMatch = titleMatchers.find(([, pattern]) => pattern.test(title));
  if (titleMatch) return titleMatch[0];

  const category = place.category?.trim() ?? "";
  const categoryMatch = categoryMatchers.find(([, pattern]) => pattern.test(category));
  if (categoryMatch) return categoryMatch[0];

  const haystack = [
    ...(place.tags ?? []),
    ...(place.searchKeywords ?? []),
    place.description,
  ]
    .filter((value): value is string => Boolean(value))
    .join(" ")
    .toLocaleLowerCase("ru-RU");

  return templateMatchers.find(([, terms]) => terms.some((term) => haystack.includes(term)))?.[0]
    ?? "generic_place";
}

export function getAttractionTemplate(place: AttractionTemplateInput): AttractionTemplateConfig {
  return attractionTemplateRegistry[determineAttractionTemplate(place)];
}
